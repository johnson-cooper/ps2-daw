def rows_to_bytes(rows, name):
    assert len(rows) == 7, name
    out = []
    for r in rows:
        assert len(r) == 5, (name, r)
        v = 0
        for i, ch in enumerate(r):
            if ch == '#':
                v |= 0x10 >> i
        out.append(v)
    return out

def main():
    codes = []
    for c in range(32, 127):
        ch = chr(c)
        assert ch in GLYPHS, "missing glyph %r" % ch
        codes.append((ch, rows_to_bytes(GLYPHS[ch], ch)))
    for name, rows in SYMBOLS:
        codes.append((name, rows_to_bytes(rows, name)))
    print("// Generated by tools/gen_font.py - do not edit by hand.")
    print("// Original 5x7 glyph design for PS2 DAW; one byte per row, bit 4 = leftmost column.")
    print('#include "ui/font.hpp"')
    print()
    print("namespace font {")
    print()
    print("const uint8_t kGlyphs[kGlyphCount][kGlyphRows] = {")
    for i, (name, b) in enumerate(codes):
        label = name if len(name) > 1 else repr(name)
        print("    {%s}, // %d %s" % (", ".join("0x%02x" % x for x in b), 32 + i, label.replace("\\", "backslash")))
    print("};")
    print()
    print("} // namespace font")

if __name__ == "__main__":
    main()
